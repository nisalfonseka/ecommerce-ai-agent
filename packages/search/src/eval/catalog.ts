const DEFAULT_UNITS = 6;

const variantId = (productId: string, size: string) =>
  `${productId}_${size.toLowerCase().replaceAll("/", "")}`;

function toProduct(spec: EvalProductSpec): Product {
  const handle = spec.id.replace(/^p_/, "").replaceAll("_", "-");
  const price = lkr(spec.priceRupees);
  return {
    id: spec.id,
    handle,
    title: spec.title,
    description: spec.description,
    url: `${BASE_URL}/products/${handle}`,
    category: spec.category,
    tags: spec.tags,
    attributes: spec.attributes,
    images: [{ url: `${BASE_URL}/images/${handle}.jpg`, alt: spec.title }],
    options: [
      { name: "color", values: [spec.color] },
      { name: "size", values: spec.sizes },
    ],
    variants: spec.sizes.map((size) => ({
      id: variantId(spec.id, size),
      productId: spec.id,
      sku: `${handle}-${size}`.toUpperCase(),
      title: `${spec.color} / ${size}`,
      options: { color: spec.color, size },
      price,
      // The memory provider derives availability from stock at read time.
      availability: "in_stock" as const,
    })),
    priceRange: { min: price, max: price },
    updatedAt: UPDATED_AT,
  };
}

/** A fresh copy of the eval store for MemoryCommerceProvider({ seed }). */
export function evalSeed(): MemorySeed {
  const products = EVAL_PRODUCTS.map(toProduct);
  const stock: Record<string, number> = {};
  for (const product of products) {
    for (const variant of product.variants) stock[variant.id] = STOCK_OVERRIDES[variant.id] ?? DEFAULT_UNITS;
  }
  return structuredClone({
    currency: "LKR",
    products,
    stock,
    orders: [],
    delivery: { fee: lkr(400), countries: ["LK"] },
  });
}
